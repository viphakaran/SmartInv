package com.smartinv.model;

public class User {
    private int id;
    private String username;
    private String password;
    private String name;
    private String role; // STORE_MANAGER, PROCUREMENT_OFFICER, SUPPLIER, ADMIN
    private String email;
    private String phone;
    private String department;

    public User() {}

    public User(int id, String username, String password, String name, String role, String email, String phone, String department) {
        this.id = id;
        this.username = username;
        this.password = password;
        this.name = name;
        this.role = role;
        this.email = email;
        this.phone = phone;
        this.department = department;
    }

    public int getId() { return id; }
    public void setId(int id) { this.id = id; }

    public String getUsername() { return username; }
    public void setUsername(String username) { this.username = username; }

    public String getPassword() { return password; }
    public void setPassword(String password) { this.password = password; }

    public String getName() { return name; }
    public void setName(String name) { this.name = name; }

    public String getRole() { return role; }
    public void setRole(String role) { this.role = role; }

    public String getEmail() { return email; }
    public void setEmail(String email) { this.email = email; }

    public String getPhone() { return phone; }
    public void setPhone(String phone) { this.phone = phone; }

    public String getDepartment() { return department; }
    public void setDepartment(String department) { this.department = department; }
}
